// Build-time only. Generates src/data/caCounties.ts from us-atlas counties-10m.json
// (US Census cartographic boundaries, public domain). Run: node scripts/generate-ca-counties.mjs
// d3-geo + topojson-client are devDependencies — NOT shipped to the runtime bundle.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { feature } from 'topojson-client';
import { geoMercator, geoPath } from 'd3-geo';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, '..');

const topo = JSON.parse(fs.readFileSync(path.join(__dirname, 'counties-10m.json'), 'utf8'));

const counties = feature(topo, topo.objects.counties).features;
const states = feature(topo, topo.objects.states).features;

// California = state FIPS "06"
const caCounties = counties.filter((f) => String(f.id).startsWith('06'));
const caState = states.find((f) => String(f.id) === '06');
if (!caState) throw new Error('California state outline (FIPS 06) not found in topojson');

// The counties Love Pathways Wraparound serves, matched by name (unique within CA).
const SERVED_NAMES = [
  'Merced', 'Calaveras', 'Contra Costa', 'San Joaquin', 'Stanislaus',
  'Alameda', 'Santa Clara', 'Madera', 'Fresno', 'Tulare',
];
const SERVED = new Set(SERVED_NAMES.map((s) => s.toLowerCase()));

// Frame fitted tightly to the SERVED counties (Northern + Central CA),
// so the served region fills the map instead of wasting space on the empty south.
const servedFC = {
  type: 'FeatureCollection',
  features: caCounties.filter((f) => SERVED.has(f.properties.name.toLowerCase())),
};
const WIDTH = 460;
const HEIGHT = 680;
const PAD = 36;
const projection = geoMercator().fitExtent([[PAD, PAD], [WIDTH - PAD, HEIGHT - PAD]], servedFC);
const pathGen = geoPath(projection);

// Round path floats to 1 decimal to shrink the inlined SVG (0.1px is plenty at 560px wide).
const round = (d) => (d == null ? '' : d.replace(/-?\d+\.\d+/g, (m) => String(+(+m).toFixed(1))));

const outline = round(pathGen(caState));

const list = caCounties
  .map((f) => {
    const name = f.properties.name;
    const served = SERVED.has(name.toLowerCase());
    const d = round(pathGen(f));
    const [cx, cy] = pathGen.centroid(f);
    return { fips: String(f.id), name, served, d, cx: +cx.toFixed(1), cy: +cy.toFixed(1) };
  })
  .sort((a, b) => a.name.localeCompare(b.name));

// Bounding box of just the served counties (for reference).
const [[sbx0, sby0], [sbx1, sby1]] = pathGen.bounds(servedFC);
const SERVED_BBOX = {
  x: +sbx0.toFixed(1),
  y: +sby0.toFixed(1),
  w: +(sbx1 - sbx0).toFixed(1),
  h: +(sby1 - sby0).toFixed(1),
};

// Verify all served counties were matched.
const matched = list.filter((c) => c.served).map((c) => c.name);
const missing = SERVED_NAMES.filter((n) => !matched.some((m) => m.toLowerCase() === n.toLowerCase()));
if (missing.length) throw new Error('Served counties not matched in topojson: ' + missing.join(', '));
console.log(`[ca-counties] matched ${matched.length}/${SERVED_NAMES.length} served, ${list.length} CA counties total`);

const ts = `// AUTO-GENERATED by scripts/generate-ca-counties.mjs — do not edit by hand.
// Source: us-atlas counties-10m.json (US Census cartographic boundaries, public domain).
// Projection: geoMercator fitted to the California outline. Coordinates are SVG pixels.

export interface CountyShape {
  fips: string;
  name: string;
  served: boolean;
  d: string;
  /** projected centroid (SVG pixels) — pin anchor */
  cx: number;
  cy: number;
}

export const MAP_WIDTH = ${WIDTH};
export const MAP_HEIGHT = ${HEIGHT};

/** Outline of the whole state of California. */
export const CA_OUTLINE = ${JSON.stringify(outline)};

/** Tight bounding box around the served counties (SVG pixels) — for a zoomed-in frame. */
export const SERVED_BBOX = ${JSON.stringify(SERVED_BBOX)};

/** All ${list.length} California counties (alphabetical). */
export const CA_COUNTIES: CountyShape[] = ${JSON.stringify(list)};

/** The ${matched.length} counties Love Pathways Wraparound serves. */
export const SERVED_COUNTIES: CountyShape[] = CA_COUNTIES.filter((c) => c.served);
`;

const outPath = path.join(root, 'src', 'data', 'caCounties.ts');
fs.writeFileSync(outPath, ts, 'utf8');
const kb = (fs.statSync(outPath).size / 1024).toFixed(1);
console.log(`[ca-counties] wrote ${outPath} (${kb} KB)`);
